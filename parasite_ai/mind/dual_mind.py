class PersonaEngine:
    """
    Pass 1 Persona Engine: Transforms user goals, screen grounding summaries,
    and episodic memory into character monologue, live thought streaming,
    and dynamic companion moods.
    """

    def __init__(
        self,
        brain_manager: Any,
        config: Optional[AppConfig] = None,
        bridge: Optional[UIBridge] = None,
    ) -> None:
        self.brain_manager = brain_manager
        self.config = config
        self.bridge = bridge

    def derive_mood(
        self,
        memory: Optional[EpisodicMemory] = None,
        state: str = "WATCHING",
        interrupted: bool = False,
        protected: bool = False,
    ) -> str:
        """
        Derives character mood badge from system state and memory strikes.
        Rules:
        - Sensitive window protected -> Cautious
        - Hardware interrupt / user override -> Curious
        - 3+ strikes (in loop) -> Panic-Averted
        - 2 strikes -> Cautious
        - Active action driving -> Focused
        - Active reasoning / thinking -> Focused
        - Default -> Curious (or Idle)
        """
        if protected:
            return "Cautious"
        if interrupted:
            return "Curious"
        if memory is not None:
            if memory.is_in_loop():
                return "Panic-Averted"
            if memory.get_consecutive_strikes() >= 2:
                return "Cautious"

        if state in ("DRIVING", "THINKING", "OFFLOADING"):
            return "Focused"
        if state == "USER_OVERRIDE":
            return "Curious"
        if state == "PROTECTED":
            return "Cautious"

        return "Curious"

    def generate_monologue(
        self,
        user_goal: str,
        scene_summary: str,
        memory_context: str,
        mood_override: Optional[str] = None,
        state: str = "THINKING",
    ) -> PersonaOutput:
        """Generates Pass 1 internal thought and character speech."""
        raw_text = ""
        if hasattr(self.brain_manager, "generate_thought"):
            raw_text = self.brain_manager.generate_thought(
                scene_summary=scene_summary,
                memory_context=memory_context,
                user_goal=user_goal,
            )
        elif hasattr(self.brain_manager, "generate"):
            system_prompt = (
                self.config.persona.system_prompt
                if self.config
                else "You are Parasite, a desktop AI companion."
            )
            prompt = (
                f"User Goal: {user_goal}\n"
                f"Scene: {scene_summary}\n"
                f"Memory: {memory_context}\n\n"
                "Provide your character observation and monologue."
            )
            raw_text = self.brain_manager.generate(
                prompt=prompt,
                system_prompt=system_prompt,
                max_tokens=256,
            )
        else:
            raw_text = f"Observing desktop for goal: {user_goal}"

        if not isinstance(raw_text, str):
            raw_text = str(raw_text)

        thought, speech = self._parse_thought_and_speech(raw_text)
        mood = mood_override or "Curious"
        logger.info("[PERSONA MONOLOGUE] State: %s | Mood: %s | Goal: %r", state, mood, user_goal)
        logger.info("  Thought: %s", thought)
        logger.info("  Speech:  %s", speech)

        if self.bridge:
            if thought:
                self.bridge.notify_thought(thought)
            if speech:
                self.bridge.notify_speech(speech)
            self.bridge.notify_state(state, mood)

        return PersonaOutput(
            thought=thought,
            speech=speech,
            mood=mood,
            state=state,
        )

    @staticmethod
    def _parse_thought_and_speech(text: str) -> Tuple[str, str]:
        """Splits raw model output into internal thought stream and dialogue speech."""
        cleaned = text.strip()
        if not cleaned:
            return "", ""

        # Check for <thought> ... </thought> tags
        if "<thought>" in cleaned and "</thought>" in cleaned:
            start = cleaned.find("<thought>") + len("<thought>")
            end = cleaned.find("</thought>")
            thought = cleaned[start:end].strip()
            speech = cleaned[end + len("</thought>"):].strip()
            return thought, speech or thought

        # Check for Thought: and Speech: prefixes
        if "thought:" in cleaned.lower() and "speech:" in cleaned.lower():
            lower = cleaned.lower()
            t_idx = lower.find("thought:")
            s_idx = lower.find("speech:")
            if t_idx < s_idx:
                thought = cleaned[t_idx + len("thought:"):s_idx].strip()
                speech = cleaned[s_idx + len("speech:"):].strip()
                return thought, speech

        # Default fallback: thought is whole text, speech is first sentence
        sentences = cleaned.split(". ")
        speech = sentences[0] + ("." if not sentences[0].endswith(".") else "")
        return cleaned, speech


