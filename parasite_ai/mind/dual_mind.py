class ActionDispatcher:
    """
    Pass 2 Action Dispatcher: Strictly parses, validates, and executes concrete
    physical actions using MouseDriver and KeyboardDriver with sub-2ms preemption.
    """

    def __init__(
        self,
        mouse_driver: Optional[Any] = None,
        keyboard_driver: Optional[Any] = None,
        bridge: Optional[UIBridge] = None,
        config: Optional[AppConfig] = None,
    ) -> None:
        self.mouse_driver = mouse_driver
        self.keyboard_driver = keyboard_driver
        self.bridge = bridge
        self.config = config

    def validate_coordinates(self, x: int, y: int) -> bool:
        """Validates that click/move coordinates reside within the virtual desktop boundaries."""
        try:
            import ctypes
            user32 = ctypes.windll.user32
            vx = user32.GetSystemMetrics(76)  # SM_XVIRTUALSCREEN
            vy = user32.GetSystemMetrics(77)  # SM_YVIRTUALSCREEN
            vw = user32.GetSystemMetrics(78)  # SM_CXVIRTUALSCREEN
            vh = user32.GetSystemMetrics(79)  # SM_CYVIRTUALSCREEN
            if vw > 0 and vh > 0:
                return vx <= x < (vx + vw) and vy <= y < (vy + vh)
        except Exception:
            pass

        # Fallback coordinate boundary check for test/headless sessions
        return 0 <= x < 10000 and 0 <= y < 10000

    def resolve_target(
        self,
        action: ActionPlan,
        som_elements: List[UIElement],
    ) -> Tuple[Optional[Tuple[int, int]], Optional[str]]:
        """Resolves target coordinates from target_id or explicit coordinates."""
        if action.target_id is not None:
            for elem in som_elements:
                if elem.id == action.target_id:
                    return (elem.center_x, elem.center_y), None
            return None, f"Target ID #{action.target_id} not found in grounded elements"

        if action.coordinates is not None:
            return action.coordinates, None

        return None, None

    def dispatch(
        self,
        action: ActionPlan,
        som_elements: List[UIElement],
        cancellation_token: Optional[threading.Event] = None,
    ) -> ActionResult:
        """Dispatches action command to physical mouse/keyboard drivers."""
        # 1. Preemption check
        if cancellation_token and cancellation_token.is_set():
            self._release_all()
            return ActionResult(
                success=False,
                interrupted=True,
                error="Interrupted by physical human input",
                action_executed=action,
            )

        # 2. Coordinate resolution
        needs_coords = action.action in (
            ActionType.CLICK,
            ActionType.DOUBLE_CLICK,
            ActionType.RIGHT_CLICK,
            ActionType.CLICK_AND_TYPE,
        )

        resolved_coords: Optional[Tuple[int, int]] = None
        if needs_coords:
            coords, err = self.resolve_target(action, som_elements)
            if err:
                return ActionResult(success=False, error=err, action_executed=action)
            if coords is None:
                return ActionResult(
                    success=False,
                    error="Target ID or coordinates required for interactive click",
                    action_executed=action,
                )
            if not self.validate_coordinates(coords[0], coords[1]):
                return ActionResult(
                    success=False,
                    error=f"Coordinates {coords} out of desktop bounds",
                    resolved_coordinates=coords,
                    action_executed=action,
                )
            resolved_coords = coords

        if self.bridge:
            self.bridge.notify_telemetry(f"Executing {action.action.value}")

        # 3. Hand Invocations
        try:
            if action.action == ActionType.CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                ok = self.mouse_driver.click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="left",
                    clicks=action.clicks,
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Mouse click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.DOUBLE_CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                ok = self.mouse_driver.double_click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="left",
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Double click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.RIGHT_CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                ok = self.mouse_driver.click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="right",
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Right click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.CLICK_AND_TYPE:
                if self.keyboard_driver:
                    ok = self.keyboard_driver.click_and_type(
                        x=resolved_coords[0],
                        y=resolved_coords[1],
                        text=action.text or "",
                        submit=action.submit,
                        cancellation_token=cancellation_token,
                        mouse_driver=self.mouse_driver,
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Click and type was cancelled or interrupted",
                            resolved_coordinates=resolved_coords,
                            action_executed=action,
                        )
                elif self.mouse_driver:
                    self.mouse_driver.click(resolved_coords[0], resolved_coords[1], cancellation_token=cancellation_token)

            elif action.action == ActionType.TYPE:
                if action.target_id is not None or action.coordinates is not None:
                    coords, err = self.resolve_target(action, som_elements)
                    if coords and self.validate_coordinates(coords[0], coords[1]) and self.keyboard_driver:
                        ok = self.keyboard_driver.click_and_type(
                            x=coords[0],
                            y=coords[1],
                            text=action.text or "",
                            submit=action.submit,
                            cancellation_token=cancellation_token,
                            mouse_driver=self.mouse_driver,
                        )
                        if not ok:
                            interrupted = bool(cancellation_token and cancellation_token.is_set())
                            return ActionResult(
                                success=False,
                                interrupted=interrupted,
                                error="Click and type was cancelled or interrupted",
                                resolved_coordinates=coords,
                                action_executed=action,
                            )
                        return ActionResult(
                            success=True,
                            resolved_coordinates=coords,
                            action_executed=action,
                        )
                # Guard: never blindly type into CompanionDock's own input box
                try:
                    import ctypes
                    user32 = ctypes.windll.user32
                    fg = user32.GetForegroundWindow()
                    if fg:
                        cbuf = ctypes.create_unicode_buffer(128)
                        user32.GetClassNameW(fg, cbuf, 128)
                        if cbuf.value == "CompanionDock":
                            edit_elem = next(
                                (e for e in som_elements if e.role in ("Edit", "Document")),
                                None,
                            )
                            if edit_elem and self.keyboard_driver:
                                ok = self.keyboard_driver.click_and_type(
                                    x=edit_elem.center_x,
                                    y=edit_elem.center_y,
                                    text=action.text or "",
                                    submit=action.submit,
                                    cancellation_token=cancellation_token,
                                    mouse_driver=self.mouse_driver,
                                )
                                return ActionResult(
                                    success=ok,
                                    resolved_coordinates=(edit_elem.center_x, edit_elem.center_y),
                                    action_executed=action,
                                    error=None if ok else "Click and type interrupted",
                                )
                            return ActionResult(
                                success=False,
                                error="Refused to type into CompanionDock prompt; focus target window or specify target_id",
                                action_executed=action,
                            )
                except Exception:
                    pass
                if self.keyboard_driver:
                    ok = self.keyboard_driver.type_text(
                        text=action.text or "",
                        submit=action.submit,
                        cancellation_token=cancellation_token,
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Type text was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.HOTKEY:
                if self.keyboard_driver:
                    keys = action.keys or [k.strip() for k in (action.text or "").split("+") if k.strip()]
                    ok = self.keyboard_driver.hotkey(*keys, cancellation_token=cancellation_token)
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Hotkey chord was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.SCROLL:
                if self.mouse_driver:
                    ok = self.mouse_driver.scroll(
                        delta=action.scroll_amount,
                        cancellation_token=cancellation_token,
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Scroll was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.WAIT:
                wait_sec = action.wait_ms / 1000.0
                if cancellation_token:
                    interrupted = cancellation_token.wait(timeout=wait_sec)
                    if interrupted:
                        return ActionResult(
                            success=False,
                            interrupted=True,
                            error="Wait interrupted by physical human input",
                            action_executed=action,
                        )
                else:
                    time.sleep(wait_sec)

            elif action.action == ActionType.PANIC:
                if self.bridge:
                    self.bridge.sig_panic_triggered.emit()
                self._release_all()
                return ActionResult(success=True, action_executed=action)

            elif action.action in (ActionType.DONE, ActionType.OFFLOAD_WEB_AI):
                return ActionResult(success=True, action_executed=action)

            return ActionResult(
                success=True,
                resolved_coordinates=resolved_coords,
                action_executed=action,
            )

        except Exception as exc:
            logger.error("Exception during action dispatch: %s", exc)
            self._release_all()
            return ActionResult(
                success=False,
                error=str(exc),
                resolved_coordinates=resolved_coords,
                action_executed=action,
            )

    def _release_all(self) -> None:
        """Emergency release of mouse buttons and keyboard keys."""
        if self.mouse_driver and hasattr(self.mouse_driver, "release_all_buttons"):
            try:
                self.mouse_driver.release_all_buttons()
            except Exception:
                pass
        if self.keyboard_driver and hasattr(self.keyboard_driver, "emergency_release_keys"):
            try:
                self.keyboard_driver.emergency_release_keys()
            except Exception:
                pass


