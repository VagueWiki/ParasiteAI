class ActionResult(BaseModel):
    """Result of dispatching an action through physical hand drivers."""
    model_config = ConfigDict(extra="ignore", validate_default=True)

    success: bool = True
    interrupted: bool = False
    error: Optional[str] = None
    resolved_coordinates: Optional[Tuple[int, int]] = None
    action_executed: Optional[ActionPlan] = None


class PersonaOutput(BaseModel):
    """Output generated by Pass 1 Persona monologue generation."""
    model_config = ConfigDict(extra="ignore", validate_default=True)

    thought: str = ""
    speech: str = ""
    mood: str = "Curious"
    state: str = "THINKING"


