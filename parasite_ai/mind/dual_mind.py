class DualMindPipeline:
    """
    Coordinates perception, safety guards, Pass 1 Persona reasoning,
    Pass 2 Action dispatching, screen diff verification, and UI telemetry.
    """

    def __init__(
        self,
        brain_manager: Any,
        memory: Optional[EpisodicMemory] = None,
        mouse_driver: Optional[Any] = None,
        keyboard_driver: Optional[Any] = None,
        screen_grounder: Optional[Any] = None,
        capturer: Optional[Any] = None,
        interrupt_guard: Optional[Any] = None,
        window_guard: Optional[Any] = None,
        bridge: Optional[UIBridge] = None,
        offloader: Optional[Any] = None,
        config: Optional[AppConfig] = None,
    ) -> None:
        self.brain_manager = brain_manager
        self.memory = memory or EpisodicMemory()
        self.mouse_driver = mouse_driver
        self.keyboard_driver = keyboard_driver
        self.screen_grounder = screen_grounder
        self.capturer = capturer
        self.interrupt_guard = interrupt_guard
        self.window_guard = window_guard
        self.bridge = bridge
        self.offloader = offloader
        self.config = config

        self.persona_engine = PersonaEngine(
            brain_manager=self.brain_manager,
            config=self.config,
            bridge=self.bridge,
        )
        self.action_dispatcher = ActionDispatcher(
            mouse_driver=self.mouse_driver,
            keyboard_driver=self.keyboard_driver,
            bridge=self.bridge,
            config=self.config,
        )

    def step(
        self,
        user_goal: str,
        screen_frame: Optional[np.ndarray] = None,
        grounded_elements: Optional[List[UIElement]] = None,
        override_action: Optional[ActionPlan] = None,
    ) -> StepRecord:
        """
        Executes a single atomic closed-loop cognitive cycle:
        1. Safety guard check (InterruptGuard, WindowGuard).
        2. Perception & grounding.
        3. Pass 1 Persona monologue generation.
        4. Pass 2 Action planning & validation.
        5. Physical execution with cancellation token.
        6. Post-action settling and screen diff calculation.
        7. Episodic memory recording and loop detector update.
        """
        # 1. Safety Guard Checks
        if self.interrupt_guard and hasattr(self.interrupt_guard, "is_interrupted"):
            if self.interrupt_guard.is_interrupted():
                if self.bridge:
                    self.bridge.notify_state("USER_OVERRIDE", "Curious")
                return self.memory.record_step(
                    action=ActionPlan(action=ActionType.WAIT, reasoning="User override active"),
                    success=False,
                    screen_diff=0.0,
                    user_goal=user_goal,
                    error_message="User override active (physical human input detected)",
                )

        if self.window_guard and hasattr(self.window_guard, "is_safe_to_operate"):
            if not self.window_guard.is_safe_to_operate():
                if self.bridge:
                    self.bridge.notify_state("PROTECTED", "Cautious")
                return self.memory.record_step(
                    action=ActionPlan(action=ActionType.WAIT, reasoning="Sensitive window active"),
                    success=False,
                    screen_diff=0.0,
                    user_goal=user_goal,
                    error_message="Sensitive window detected; pausing actions",
                )

        # 2. Perception & Grounding
        current_frame = screen_frame
        if current_frame is None and self.capturer:
            try:
                current_frame = self.capturer.capture_screen()
            except Exception as exc:
                logger.debug("Failed capturing screen frame: %s", exc)

        elements = grounded_elements
        if elements is None and self.screen_grounder:
            try:
                elements = self.screen_grounder.ground(image_override=current_frame)
            except Exception as exc:
                logger.debug("Failed grounding screen elements: %s", exc)
                elements = []

        elements = elements or []

        if self.bridge:
            self.bridge.set_hud_targets(elements)
            if current_frame is not None:
                self.bridge.notify_perception(current_frame, elements)

        pre_hash = compute_dhash(current_frame) if current_frame is not None else None

        # 3. Pass 1: Persona Engine
        current_mood = self.persona_engine.derive_mood(self.memory, state="THINKING")
        scene_summary = (
            self.screen_grounder.format_som_summary(elements)
            if self.screen_grounder and hasattr(self.screen_grounder, "format_som_summary")
            else f"{len(elements)} targets detected"
        )
        memory_context = self.memory.format_for_prompt()

        persona_out = self.persona_engine.generate_monologue(
            user_goal=user_goal,
            scene_summary=scene_summary,
            memory_context=memory_context,
            mood_override=current_mood,
            state="THINKING",
        )

        # 4. Pass 2: Action Planning
        if override_action is not None:
            action_plan = override_action
        elif self.memory.is_in_loop():
            # Detected cognitive failure loop! Trigger emergency strategy switch
            action_plan = ActionPlan(
                action=ActionType.PANIC,
                reasoning="Detected 3-strike failure loop. Initiating panic/strategy reset.",
            )
        else:
            som_dicts = [
                {
                    "id": e.id,
                    "role": e.role,
                    "label": e.label,
                    "x": e.x,
                    "y": e.y,
                    "width": e.width,
                    "height": e.height,
                }
                for e in elements
            ]
            raw_action = self.brain_manager.generate_action(
                persona_intent=f"User Goal: {user_goal}\nIntent: {persona_out.thought}",
                som_elements=som_dicts,
                memory_context=memory_context,
            )
            action_plan = ActionPlan.model_validate(raw_action)
            if action_plan.action == ActionType.OFFLOAD_WEB_AI:
                goal_lower = user_goal.lower()
                wants_offload = any(
                    kw in goal_lower
                    for kw in ("gemini", "web ai", "offload", "browser ai", "chatgpt", "claude", "ask ai", "ask browser")
                )
                if not wants_offload:
                    app_map = {
                        "notepad": "notepad",
                        "calculator": "calc",
                        "calc": "calc",
                        "paint": "mspaint",
                        "cmd": "cmd",
                        "command prompt": "cmd",
                        "powershell": "powershell",
                        "explorer": "explorer",
                        "file explorer": "explorer",
                    }
                    matched_cmd = next((cmd for name, cmd in app_map.items() if name in goal_lower), None)
                    if matched_cmd and any(w in goal_lower for w in ("open", "launch", "start", "run")):
                        run_edit = next(
                            (e for e in elements if e.role == "Edit" and ("open" in e.label.lower() or "type the name" in e.label.lower())),
                            None,
                        )
                        if run_edit:
                            action_plan = ActionPlan(
                                action=ActionType.CLICK_AND_TYPE,
                                target_id=run_edit.id,
                                text=matched_cmd,
                                submit=True,
                                reasoning=f"Type '{matched_cmd}' into Run dialog and press Enter",
                            )
                        else:
                            action_plan = ActionPlan(
                                action=ActionType.HOTKEY,
                                keys=["win", "r"],
                                reasoning=f"Open Windows Run dialog (Win+R) to launch {matched_cmd}",
                            )
                    else:
                        action_plan = ActionPlan(
                            action=ActionType.WAIT,
                            wait_ms=500,
                            reasoning="Skipping unrequested browser offload in local mode; re-grounding desktop",
                        )

        # 5. Execution State & Dispatch
        if action_plan.action == ActionType.OFFLOAD_WEB_AI:
            driving_state = "OFFLOADING"
        elif action_plan.action == ActionType.WAIT:
            driving_state = "WATCHING"
        elif action_plan.action == ActionType.DONE:
            driving_state = "WATCHING"
        else:
            driving_state = "DRIVING"

        driving_mood = self.persona_engine.derive_mood(self.memory, state=driving_state)
        if self.bridge:
            self.bridge.notify_state(driving_state, driving_mood)

        token = (
            self.interrupt_guard.get_cancellation_token()
            if self.interrupt_guard and hasattr(self.interrupt_guard, "get_cancellation_token")
            else None
        )

        if action_plan.action == ActionType.OFFLOAD_WEB_AI and self.offloader:
            try:
                harvested = self.offloader.query_web_ai(user_goal)
                if isinstance(harvested, str) and harvested.strip():
                    persona_out.thought = f"{persona_out.thought}\n[Web AI Advice]: {harvested.strip()}"
                    persona_out.speech = f"Web AI advises: {harvested.strip()[:180]}"
                    if self.bridge:
                        self.bridge.notify_speech(persona_out.speech)
                action_res = ActionResult(success=True, action_executed=action_plan)
            except Exception as exc:
                action_res = ActionResult(success=False, error=str(exc), action_executed=action_plan)
        else:
            action_res = self.action_dispatcher.dispatch(
                action=action_plan,
                som_elements=elements,
                cancellation_token=token,
            )

        # 6. Settling & Screen Diff
        post_frame = current_frame
        if action_res.success and action_plan.action in INTERACTIVE_ACTION_TYPES and not action_res.interrupted:
            time.sleep(0.05)
            if self.capturer:
                try:
                    post_frame = self.capturer.capture_screen()
                except Exception:
                    pass

        post_hash = compute_dhash(post_frame) if post_frame is not None else None
        screen_diff = (
            compute_pixel_diff(current_frame, post_frame)
            if (current_frame is not None and post_frame is not None)
            else 0.0
        )

        # 7. Episodic Memory Recording
        target_info = None
        if action_plan.target_id:
            matched = next((e for e in elements if e.id == action_plan.target_id), None)
            if matched:
                target_info = {
                    "id": matched.id,
                    "role": matched.role,
                    "label": matched.label,
                    "bbox": matched.bbox,
                }

        step_record = self.memory.record_step(
            action=action_plan,
            success=action_res.success,
            screen_diff=screen_diff,
            user_goal=user_goal,
            persona_thought=persona_out.thought,
            persona_speech=persona_out.speech,
            target_info=target_info,
            pre_hash=pre_hash,
            post_hash=post_hash,
            error_message=action_res.error,
        )

        # Post-action telemetry & cleanup
        if action_plan.action == ActionType.DONE:
            if self.bridge:
                self.bridge.notify_state("WATCHING", "Amused")
                self.bridge.clear_hud_targets()

        if action_res.interrupted:
            if self.bridge:
                self.bridge.notify_state("USER_OVERRIDE", "Curious")

        return step_record
