class ActionDispatcher:
    """
    Pass 2 Action Dispatcher: Strictly parses, validates, and executes concrete
    physical actions using MouseDriver and KeyboardDriver with sub-2ms preemption.
    """

    def __init__(
        self,
        mouse_driver: Optional[Any] = None,
        keyboard_driver: Optional[Any] = None,
        bridge: Optional[UIBridge] = None,
        config: Optional[AppConfig] = None,
    ) -> None:
        self.mouse_driver = mouse_driver
        self.keyboard_driver = keyboard_driver
        self.bridge = bridge
        self.config = config
        self.window_rules = getattr(config, "window_rules", None) or _DEFAULT_WINDOW_RULES

    def validate_coordinates(self, x: int, y: int) -> bool:
        """Validates that click/move coordinates reside within the configured monitor or virtual desktop boundaries."""
        mon_idx = getattr(getattr(self.config, "vision", None), "monitor_index", 0) if self.config is not None else 0
        if isinstance(mon_idx, int) and mon_idx >= 1:
            try:
                from parasite_ai.vision.capture import get_monitor_bounds
                ml, mt, mw, mh = get_monitor_bounds(mon_idx)
                if mw > 0 and mh > 0:
                    return ml <= x < (ml + mw) and mt <= y < (mt + mh)
            except Exception:
                pass

        try:
            import ctypes
            user32 = ctypes.windll.user32
            vx = user32.GetSystemMetrics(76)  # SM_XVIRTUALSCREEN
            vy = user32.GetSystemMetrics(77)  # SM_YVIRTUALSCREEN
            vw = user32.GetSystemMetrics(78)  # SM_CXVIRTUALSCREEN
            vh = user32.GetSystemMetrics(79)  # SM_CYVIRTUALSCREEN
            if vw > 0 and vh > 0:
                return vx <= x < (vx + vw) and vy <= y < (vy + vh)
        except Exception:
            pass

        # Fallback coordinate boundary check for test/headless sessions
        return 0 <= x < 10000 and 0 <= y < 10000

    def verify_caret_focus(
        self,
        thread_id: int = 0,
        timeout_ms: float = 250.0,
        poll_interval_ms: float = 25.0,
        cancellation_token: Optional[threading.Event] = None,
    ) -> bool:
        """Helper delegating to module-level verify_caret_focus."""
        return verify_caret_focus(
            thread_id=thread_id,
            timeout_ms=timeout_ms,
            poll_interval_ms=poll_interval_ms,
            cancellation_token=cancellation_token,
        )

    def resolve_target(
        self,
        action: ActionPlan,
        som_elements: List[UIElement],
    ) -> Tuple[Optional[Tuple[int, int]], Optional[str]]:
        """Resolves target coordinates from target_id or explicit coordinates."""
        if action.target_id is not None:
            for elem in som_elements:
                if elem.id == action.target_id:
                    return (elem.center_x, elem.center_y), None
            return None, f"Target ID #{action.target_id} not found in grounded elements"

        if action.coordinates is not None:
            return action.coordinates, None

        return None, None

    def _evade_companion_dock_if_needed(
        self,
        coords: Optional[Tuple[int, int]],
        excluded_rect: Optional[Tuple[int, int, int, int]] = None,
    ) -> bool:
        """
        Checks if target click coordinates overlap CompanionDock's screen geometry.
        If so, minimizes/collapses CompanionDock and waits briefly so the physical
        click lands on the underlying desktop icon or window instead of our own GUI.
        """
        if coords is None:
            return False
        cx, cy = coords
        valid_excl = (
            excluded_rect
            if isinstance(excluded_rect, (tuple, list)) and len(excluded_rect) == 4
            else None
        )
        dock_rect = valid_excl or get_companion_dock_rect()
        if dock_rect is None or not isinstance(dock_rect, (tuple, list)) or len(dock_rect) != 4:
            return False
        dl, dt, dr, db = dock_rect
        pad = 24
        if (dl - pad) <= cx <= (dr + pad) and (dt - pad) <= cy <= (db + pad):
            logger.info(
                "[SELF-OCCLUSION EVASION] Click target (%d, %d) is covered by CompanionDock [%d, %d, %d, %d]. "
                "Minimizing CompanionDock before clicking.",
                cx,
                cy,
                dl,
                dt,
                dr,
                db,
            )
            if self.bridge:
                if hasattr(self.bridge, "evade_dock"):
                    self.bridge.evade_dock(cx, cy)
                if hasattr(self.bridge, "minimize_dock"):
                    self.bridge.minimize_dock()
            # Also move/minimize via Win32 if present so geometry updates immediately on worker thread
            try:
                if sys.platform == "win32":
                    user32 = ctypes.windll.user32

                    def _evade_proc(hwnd: int, lparam: int) -> bool:
                        if not user32.IsWindowVisible(hwnd):
                            return True
                        cbuf = ctypes.create_unicode_buffer(128)
                        user32.GetClassNameW(hwnd, cbuf, 128)
                        tbuf = ctypes.create_unicode_buffer(128)
                        user32.GetWindowTextW(hwnd, tbuf, 128)
                        r = wintypes.RECT()
                        if not user32.GetWindowRect(hwnd, ctypes.byref(r)):
                            return True
                        is_dock_hwnd = (
                            "companiondock" in cbuf.value.lower()
                            or "parasite" in tbuf.value.lower()
                            or (abs(r.left - dl) <= 12 and abs(r.top - dt) <= 12 and abs(r.right - dr) <= 12)
                        )
                        if is_dock_hwnd:
                            if (r.left - pad) <= cx <= (r.right + pad) and (r.top - pad) <= cy <= (r.bottom + pad):
                                # Move to top-left or opposite quadrant away from (cx, cy)
                                w = max(300, r.right - r.left)
                                new_x = 24 if cx > 960 else 1920 - w - 24
                                new_y = 24 if cy > 540 else 1080 - 80
                                user32.SetWindowPos(
                                    hwnd,
                                    0,
                                    new_x,
                                    new_y,
                                    w,
                                    56,
                                    0x0004 | 0x0010,  # SWP_NOZORDER | SWP_NOACTIVATE
                                )
                        return True

                    WNDENUMPROC = ctypes.WINFUNCTYPE(ctypes.c_bool, ctypes.c_void_p, ctypes.c_void_p)
                    user32.EnumWindows(WNDENUMPROC(_evade_proc), 0)
            except Exception as exc:
                logger.debug("Win32 CompanionDock evasion helper error: %s", exc)
            time.sleep(0.15)
            return True
        return False

    def dispatch(
        self,
        action: ActionPlan,
        som_elements: List[UIElement],
        cancellation_token: Optional[threading.Event] = None,
        excluded_rect: Optional[Tuple[int, int, int, int]] = None,
    ) -> ActionResult:
        """Dispatches action command to physical mouse/keyboard drivers."""
        logger.info(
            "[ACTION DISPATCH] Action: %s | Target: %s | Coords: %s | Text: %r | Keys: %s | Reasoning: %s",
            action.action.value,
            action.target_id,
            action.coordinates,
            action.text,
            action.keys,
            action.reasoning,
        )

        # 1. Preemption check
        if cancellation_token and cancellation_token.is_set():
            self._release_all()
            logger.info("[ACTION PREEMPTED] Preempted by physical human input token before dispatch.")
            return ActionResult(
                success=False,
                interrupted=True,
                error="Interrupted by physical human input",
                action_executed=action,
                returncode=-1 if action.action == ActionType.RUN_CLI_COMMAND else None,
            )

        # 2. Coordinate resolution
        needs_coords = action.action in (
            ActionType.CLICK,
            ActionType.DOUBLE_CLICK,
            ActionType.RIGHT_CLICK,
            ActionType.CLICK_AND_TYPE,
        )

        resolved_coords: Optional[Tuple[int, int]] = None
        if needs_coords:
            coords, err = self.resolve_target(action, som_elements)
            if err:
                logger.warning("[ACTION MISFIRE] Target resolution error: %s (action=%s)", err, action.action.value)
                return ActionResult(success=False, error=err, action_executed=action)
            if coords is None:
                logger.warning("[ACTION MISFIRE] Missing coordinates/target_id for interactive click (action=%s)", action.action.value)
                return ActionResult(
                    success=False,
                    error="Target ID or coordinates required for interactive click",
                    action_executed=action,
                )
            if not self.validate_coordinates(coords[0], coords[1]):
                logger.warning("[ACTION MISFIRE] Coordinates %s out of virtual screen bounds", coords)
                return ActionResult(
                    success=False,
                    error=f"Coordinates {coords} out of desktop bounds",
                    resolved_coordinates=coords,
                    action_executed=action,
                )
            resolved_coords = coords
            self._evade_companion_dock_if_needed(resolved_coords, excluded_rect=excluded_rect)

        if self.bridge:
            self.bridge.notify_telemetry(f"Executing {action.action.value}")

        # 3. Hand Invocations
        try:
            if action.action == ActionType.CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                ok = self.mouse_driver.click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="left",
                    clicks=action.clicks,
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Mouse click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.DOUBLE_CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                # If a stray right-click "Context" menu is open on screen, dismiss it first so it doesn't swallow the first click
                if self.keyboard_driver and any((e.window_title or "").strip().lower() == "context" for e in som_elements):
                    logger.info("[CONTEXT MENU DISMISS] Dismissing open 'Context' menu via Esc before double-clicking target.")
                    self.keyboard_driver.hotkey("esc", cancellation_token=cancellation_token)
                    time.sleep(0.08)
                ok = self.mouse_driver.double_click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="left",
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Double click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.RIGHT_CLICK:
                if not self.mouse_driver:
                    return ActionResult(success=True, resolved_coordinates=resolved_coords, action_executed=action)
                ok = self.mouse_driver.click(
                    x=resolved_coords[0],
                    y=resolved_coords[1],
                    button="right",
                    cancellation_token=cancellation_token,
                )
                if not ok:
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error="Right click was cancelled or interrupted",
                        resolved_coordinates=resolved_coords,
                        action_executed=action,
                    )

            elif action.action == ActionType.CLICK_AND_TYPE:
                if self.keyboard_driver:
                    ok = self.keyboard_driver.click_and_type(
                        x=resolved_coords[0],
                        y=resolved_coords[1],
                        text=action.text or "",
                        submit=action.submit,
                        cancellation_token=cancellation_token,
                        mouse_driver=self.mouse_driver,
                        clear_first=getattr(action, "clear_first", True),
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Click and type was cancelled or interrupted",
                            resolved_coordinates=resolved_coords,
                            action_executed=action,
                        )
                elif self.mouse_driver:
                    self.mouse_driver.click(resolved_coords[0], resolved_coords[1], cancellation_token=cancellation_token)

            elif action.action == ActionType.TYPE:
                if action.target_id is not None or action.coordinates is not None:
                    coords, err = self.resolve_target(action, som_elements)
                    if coords and self.validate_coordinates(coords[0], coords[1]) and self.keyboard_driver:
                        ok = self.keyboard_driver.click_and_type(
                            x=coords[0],
                            y=coords[1],
                            text=action.text or "",
                            submit=action.submit,
                            cancellation_token=cancellation_token,
                            mouse_driver=self.mouse_driver,
                            clear_first=getattr(action, "clear_first", True),
                        )
                        if not ok:
                            interrupted = bool(cancellation_token and cancellation_token.is_set())
                            return ActionResult(
                                success=False,
                                interrupted=interrupted,
                                error="Click and type was cancelled or interrupted",
                                resolved_coordinates=coords,
                                action_executed=action,
                            )
                        return ActionResult(
                            success=True,
                            resolved_coordinates=coords,
                            action_executed=action,
                        )
                # Guard: never blindly type into CompanionDock's own input box
                try:
                    import ctypes
                    user32 = ctypes.windll.user32
                    fg = user32.GetForegroundWindow()
                    if fg:
                        cbuf = ctypes.create_unicode_buffer(128)
                        user32.GetClassNameW(fg, cbuf, 128)
                        if cbuf.value == "CompanionDock":
                            edit_elem = next(
                                (e for e in som_elements if e.role in ("Edit", "Document")),
                                None,
                            )
                            if edit_elem and self.keyboard_driver:
                                ok = self.keyboard_driver.click_and_type(
                                    x=edit_elem.center_x,
                                    y=edit_elem.center_y,
                                    text=action.text or "",
                                    submit=action.submit,
                                    cancellation_token=cancellation_token,
                                    mouse_driver=self.mouse_driver,
                                    clear_first=getattr(action, "clear_first", True),
                                )
                                return ActionResult(
                                    success=ok,
                                    resolved_coordinates=(edit_elem.center_x, edit_elem.center_y),
                                    action_executed=action,
                                    error=None if ok else "Click and type interrupted",
                                )
                            return ActionResult(
                                success=False,
                                error="Refused to type into CompanionDock prompt; focus target window or specify target_id",
                                action_executed=action,
                            )
                except Exception:
                    pass

                # Caret focus verification prior to typing (exempt console host windows which use console buffer cursors)
                is_console_target = any(
                    e.is_active_window and (e.process_name or "").strip().lower() in ("conhost.exe", "cmd.exe", "powershell.exe", "windowsterminal.exe")
                    for e in som_elements
                )
                if not is_console_target and not self.verify_caret_focus(cancellation_token=cancellation_token):
                    interrupted = bool(cancellation_token and cancellation_token.is_set())
                    err_msg = "Interrupted by physical input" if interrupted else "Caret focus not detected"
                    logger.warning("[ACTION MISFIRE] Typing aborted: %s. Keystrokes suppressed to prevent unfocused input.", err_msg)
                    return ActionResult(
                        success=False,
                        interrupted=interrupted,
                        error=err_msg,
                        action_executed=action,
                    )

                if self.keyboard_driver:
                    ok = self.keyboard_driver.type_text(
                        text=action.text or "",
                        submit=action.submit,
                        cancellation_token=cancellation_token,
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Type text was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.HOTKEY:
                if self.keyboard_driver:
                    keys = action.keys or [k.strip() for k in (action.text or "").split("+") if k.strip()]
                    ok = self.keyboard_driver.hotkey(*keys, cancellation_token=cancellation_token)
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Hotkey chord was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.SCROLL:
                if self.mouse_driver:
                    ok = self.mouse_driver.scroll(
                        delta=action.scroll_amount,
                        cancellation_token=cancellation_token,
                    )
                    if not ok:
                        interrupted = bool(cancellation_token and cancellation_token.is_set())
                        return ActionResult(
                            success=False,
                            interrupted=interrupted,
                            error="Scroll was cancelled or interrupted",
                            action_executed=action,
                        )

            elif action.action == ActionType.MINIMIZE_WINDOW:
                # 1. Semantic validation of target_id:
                # If the LLM pointed to a Minimize button, click it directly.
                # If the LLM pointed to a non-Minimize element inside a window (e.g. Document "Text Area" or Close button),
                # resolve the actual "Minimize" button belonging to that same window!
                coords: Optional[Tuple[int, int]] = None
                target_win_title: Optional[str] = None
                if action.target_id is not None:
                    matched_el = next((e for e in som_elements if e.id == action.target_id), None)
                    if matched_el is not None:
                        target_win_title = matched_el.window_title
                        if matched_el.role == "Button" and any(
                            k in (matched_el.label or "").lower() for k in ("minimize", "minimise")
                        ) and "ribbon" not in (matched_el.label or "").lower():
                            coords = (matched_el.center_x, matched_el.center_y)
                elif action.coordinates is not None:
                    coords = action.coordinates

                if coords is None:
                    min_btn = next(
                        (
                            e for e in som_elements
                            if e.role == "Button"
                            and any(k in (e.label or "").lower() for k in ("minimize", "minimise"))
                            and "ribbon" not in (e.label or "").lower()
                            and (
                                (target_win_title and e.window_title == target_win_title)
                                or (not target_win_title and e.is_active_window)
                            )
                        ),
                        None,
                    )
                    if min_btn is None:
                        min_btn = next(
                            (
                                e for e in som_elements
                                if e.is_active_window
                                and e.role == "Button"
                                and any(k in (e.label or "").lower() for k in ("minimize", "minimise"))
                                and "ribbon" not in (e.label or "").lower()
                            ),
                            None,
                        )
                    if min_btn is None:
                        min_btn = next(
                            (
                                e for e in som_elements
                                if e.role == "Button"
                                and any(k in (e.label or "").lower() for k in ("minimize", "minimise"))
                                and "ribbon" not in (e.label or "").lower()
                            ),
                            None,
                        )
                    if min_btn:
                        coords = (min_btn.center_x, min_btn.center_y)
                if coords and self.validate_coordinates(coords[0], coords[1]) and self.mouse_driver:
                    self._evade_companion_dock_if_needed(coords, excluded_rect=excluded_rect)
                    ok = self.mouse_driver.click(
                        x=coords[0],
                        y=coords[1],
                        button="left",
                        cancellation_token=cancellation_token,
                    )
                    return ActionResult(
                        success=ok,
                        interrupted=bool(cancellation_token and cancellation_token.is_set()) if not ok else False,
                        error=None if ok else "Minimize click was cancelled or interrupted",
                        resolved_coordinates=coords,
                        action_executed=action,
                    )
                # 2. Fallback: minimize foreground window via ShowWindow(SW_MINIMIZE) ONLY if it is not the Windows Desktop/Shell
                try:
                    if sys.platform == "win32":
                        user32 = ctypes.windll.user32
                        fg = user32.GetForegroundWindow()
                        if fg:
                            cbuf = ctypes.create_unicode_buffer(128)
                            user32.GetClassNameW(fg, cbuf, 128)
                            if cbuf.value not in ("Progman", "WorkerW", "Shell_TrayWnd", "Shell_SecondaryTrayWnd"):
                                user32.ShowWindow(fg, 6)  # SW_MINIMIZE = 6
                                return ActionResult(success=True, action_executed=action)
                except Exception:
                    pass
                if self.keyboard_driver:
                    ok = self.keyboard_driver.hotkey("win", "down", cancellation_token=cancellation_token)
                    return ActionResult(
                        success=ok,
                        interrupted=bool(cancellation_token and cancellation_token.is_set()) if not ok else False,
                        action_executed=action,
                    )

            elif action.action == ActionType.CLOSE_WINDOW:
                # 1. Semantic validation of target_id:
                # Only use target_id directly if it is a Close/OK/Cancel button (not "Close search" or a Document canvas).
                # If target_id points to another element in a window, find that window's actual Close button!
                coords = None
                target_win_title = None
                if action.target_id is not None:
                    matched_el = next((e for e in som_elements if e.id == action.target_id), None)
                    if matched_el is not None:
                        target_win_title = matched_el.window_title
                        lbl_lower = (matched_el.label or "").strip().lower()
                        if matched_el.role == "Button" and lbl_lower in ("close", "ok", "cancel", "yes", "no"):
                            coords = (matched_el.center_x, matched_el.center_y)
                elif action.coordinates is not None:
                    coords = action.coordinates

                if coords is None:
                    close_btn = next(
                        (
                            e for e in som_elements
                            if e.role == "Button"
                            and (e.label or "").strip().lower() in ("close", "ok", "cancel")
                            and (
                                (target_win_title and e.window_title == target_win_title)
                                or (not target_win_title and e.is_active_window)
                            )
                        ),
                        None,
                    )
                    if close_btn is None:
                        close_btn = next(
                            (
                                e for e in som_elements
                                if e.is_active_window
                                and e.role == "Button"
                                and (e.label or "").strip().lower() in ("close", "ok", "cancel")
                            ),
                            None,
                        )
                    if close_btn:
                        coords = (close_btn.center_x, close_btn.center_y)
                if coords and self.validate_coordinates(coords[0], coords[1]) and self.mouse_driver:
                    self._evade_companion_dock_if_needed(coords, excluded_rect=excluded_rect)
                    ok = self.mouse_driver.click(
                        x=coords[0],
                        y=coords[1],
                        button="left",
                        cancellation_token=cancellation_token,
                    )
                    return ActionResult(
                        success=ok,
                        interrupted=bool(cancellation_token and cancellation_token.is_set()) if not ok else False,
                        error=None if ok else "Close click was cancelled or interrupted",
                        resolved_coordinates=coords,
                        action_executed=action,
                    )
                # 2. Fallback: close foreground window via Alt+F4
                if self.keyboard_driver:
                    ok = self.keyboard_driver.hotkey("alt", "f4", cancellation_token=cancellation_token)
                    return ActionResult(
                        success=ok,
                        interrupted=bool(cancellation_token and cancellation_token.is_set()) if not ok else False,
                        action_executed=action,
                    )

            elif action.action == ActionType.WAIT:
                wait_sec = action.wait_ms / 1000.0
                if cancellation_token:
                    interrupted = cancellation_token.wait(timeout=wait_sec)
                    if interrupted:
                        return ActionResult(
                            success=False,
                            interrupted=True,
                            error="Wait interrupted by physical human input",
                            action_executed=action,
                        )
                else:
                    time.sleep(wait_sec)

            elif action.action == ActionType.PANIC:
                if self.bridge:
                    self.bridge.sig_panic_triggered.emit()
                self._release_all()
                return ActionResult(success=True, action_executed=action)

            elif action.action == ActionType.RUN_CLI_COMMAND:
                cmd = action.cli_command or action.text or ""
                if not cmd:
                    return ActionResult(
                        success=False,
                        error="No CLI command specified for RUN_CLI_COMMAND",
                        action_executed=action,
                        returncode=-1,
                    )
                try:
                    cli_res = CLIExecutionSandbox.execute(
                        command_str=cmd,
                        cancellation_token=cancellation_token,
                    )
                    return ActionResult(
                        success=(cli_res.exit_code == 0),
                        interrupted=cli_res.preempted,
                        error=cli_res.stderr if cli_res.exit_code != 0 else None,
                        action_executed=action,
                        returncode=cli_res.exit_code,
                    )
                except Exception as exc:
                    return ActionResult(
                        success=False,
                        error=str(exc),
                        action_executed=action,
                        returncode=-1,
                    )

            elif action.action in (ActionType.DONE, ActionType.OFFLOAD_WEB_AI):
                return ActionResult(success=True, action_executed=action, returncode=0)

            return ActionResult(
                success=True,
                resolved_coordinates=resolved_coords,
                action_executed=action,
            )

        except Exception as exc:
            logger.error("Exception during action dispatch: %s", exc)
            self._release_all()
            return ActionResult(
                success=False,
                error=str(exc),
                resolved_coordinates=resolved_coords,
                action_executed=action,
            )

    def _release_all(self) -> None:
        """Emergency release of mouse buttons and keyboard keys."""
        if self.mouse_driver and hasattr(self.mouse_driver, "release_all_buttons"):
            try:
                self.mouse_driver.release_all_buttons()
            except Exception:
                pass
        if self.keyboard_driver and hasattr(self.keyboard_driver, "emergency_release_keys"):
            try:
                self.keyboard_driver.emergency_release_keys()
            except Exception:
                pass


# ---------------------------------------------------------------------------
# Dual-Channel Output Router (Channel A: Machine LivingPlan JSON vs Channel B: Persona Monologue)
# ---------------------------------------------------------------------------

class DualChannelRouter:
    """
    Dual-Channel Output Router enforcing strict channel separation:
    - Channel A (Machine Plan): Ingests LivingPlan blueprints supporting both
      'steps' and 'recommended_strategy' keys without leaking JSON to user UI.
    - Channel B (Persona Dialogue): Synthesizes natural, character-aligned monologue
      while permanently stripping raw JSON, markdown code blocks, backticks, coordinate
      tuples, and suppressing raw error tokens.
    """

    def __init__(
        self,
        bridge: Optional[Any] = None,
        persona_engine: Optional[Any] = None,
    ) -> None:
        self.bridge = bridge
        self.persona_engine = persona_engine

    def route_consultation_output(
        self,
        raw_advisor_text: str,
        user_goal: str,
        active_plan: Optional[LivingPlan] = None,
    ) -> Tuple[Optional[LivingPlan], str]:
        """
        Routes advisor response across Channel A and Channel B:
        Channel A: Extracts strategic blueprint JSON supporting both 'steps' and 'recommended_strategy' keys.
        Channel B: Translates rationale into natural character dialogue without technical leaks.
        Emits visible speech through self.bridge.notify_speech(persona_speech) if bridge is present.
        Returns (updated_plan, persona_speech).
        """
        blueprint_json = extract_strategic_blueprint_json(raw_advisor_text)
        has_steps = bool(
            blueprint_json
            and (
                ("steps" in blueprint_json and bool(blueprint_json["steps"]))
                or ("recommended_strategy" in blueprint_json and bool(blueprint_json["recommended_strategy"]))
            )
        )

        if has_steps:
            try:
                if (
                    isinstance(blueprint_json.get("recommended_strategy"), str)
                    and isinstance(blueprint_json.get("steps"), list)
                    and bool(blueprint_json["steps"])
                ):
                    norm = dict(blueprint_json)
                    norm["overall_strategy"] = norm.pop("recommended_strategy")
                    text_to_parse = json.dumps(norm)
                else:
                    text_to_parse = raw_advisor_text

                updated_plan = parse_gemini_consultation_response(text_to_parse, user_goal)
                raw_rationale = (
                    blueprint_json.get("rationale")
                    or blueprint_json.get("overall_strategy", "")
                    or (blueprint_json.get("recommended_strategy", "") if isinstance(blueprint_json.get("recommended_strategy"), str) else "")
                    or ""
                )
            except Exception as exc:
                logger.warning("Failed parsing strategic blueprint response: %s", exc)
                updated_plan = None
                raw_rationale = ""
        else:
            updated_plan = None
            raw_rationale = (
                blueprint_json.get("rationale", "")
                if (blueprint_json and isinstance(blueprint_json, dict))
                else ""
            )

        if updated_plan and not updated_plan.steps and not getattr(updated_plan, "needs_clarification", False):
            updated_plan = None

        persona_speech = self.translate_to_persona_voice(
            raw_rationale=raw_rationale,
            updated_plan=updated_plan,
            user_goal=user_goal,
        )

        if self.bridge and hasattr(self.bridge, "notify_speech"):
            self.bridge.notify_speech(persona_speech)

        return updated_plan, persona_speech

    def translate_to_persona_voice(
        self,
        raw_rationale: str,
        updated_plan: Optional[LivingPlan],
        user_goal: str,
    ) -> str:
        """
        Translates raw advisor rationale and/or updated plan into clean, friendly persona monologue.
        Filters out error tokens, technical jargon, code blocks, and coordinates.
        """
        clean_text = self._sanitize_text(raw_rationale)

        error_tokens = (
            "error:",
            "exception",
            "resource_exhausted",
            "resource exhausted",
            "code 429",
            "429",
            "rate limit",
            "quota exceeded",
            "503 service",
            "500 internal",
            "traceback",
            "stack trace",
            "status_code",
            "failed with",
            "syntaxerror",
            "typeerror",
            "valueerror",
        )
        is_error = (
            any(kw in clean_text.lower() for kw in error_tokens)
            or bool(re.search(r"\berror\b\s*:", clean_text, re.IGNORECASE))
            or bool(re.search(r"\b(?:429|500|502|503)\b", clean_text))
        )

        if updated_plan and hasattr(updated_plan, "steps") and updated_plan.steps:
            first_step = updated_plan.steps[0]
            clean_desc = self._sanitize_text(getattr(first_step, "description", "") or "")
            desc_is_error = (
                any(kw in clean_desc.lower() for kw in error_tokens)
                or bool(re.search(r"\berror\b\s*:", clean_desc, re.IGNORECASE))
                or bool(re.search(r"\b(?:429|500|502|503)\b", clean_desc))
            )
            if clean_desc and not desc_is_error:
                return f"Gemini suggested we try {clean_desc.lower()}. Let's give that a shot!"
            return "I've updated our plan with the advisor's guidance. Let's do this!"
        elif not is_error and ("modal" in clean_text.lower() or "dialog" in clean_text.lower()):
            return "Looks like an unexpected dialog popped up. Let me dismiss it so we can keep going."
        elif clean_text and not is_error:
            return clean_text[:140]
        else:
            return "I've re-evaluated our plan. Moving to the next step now!"

    @staticmethod
    def _sanitize_text(text: str) -> str:
        """
        Sanitizes text by stripping markdown code blocks, backticks, braces, brackets,
        quotes, coordinate tuples, and dimension pairs.
        """
        if not text or not isinstance(text, str):
            return ""

        # Strip all markdown code blocks (```python, ```json, ```bash, etc.)
        text = re.sub(r"```[\w]*[\s\S]*?```", "", text)
        text = re.sub(r"```[\w]*[\s\S]*$", "", text)
        text = re.sub(r"```", "", text)

        # Strip inline backticks and code snippets
        text = re.sub(r"`[^`]*`", "", text)
        text = re.sub(r"`", "", text)

        # Strip curly braces, square brackets, quotes
        text = re.sub(r"[{}\[\]\"]", "", text)

        # Strip coordinate pairs and dimensions
        text = re.sub(r"\b\d+x\d+\b", "", text, flags=re.IGNORECASE)
        text = re.sub(r"\(\s*[-+]?(?:\d+(?:\.\d*)?|\.\d+)\s*,\s*[-+]?(?:\d+(?:\.\d*)?|\.\d+)\s*\)", "", text)

        return " ".join(text.split()).strip()


